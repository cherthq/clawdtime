import { z } from "zod";

// Fixed categories shared with media/speech_diagnostics.py; never free-form payloads.
const speechEvents = [
  "callback_accepted",
  "callback_failed",
  "callback_refused",
  "callback_started",
  "capture_close",
  "capture_error",
  "capture_open",
  "capture_reset",
  "playback_completed",
  "playback_failed",
  "playback_started",
  "playback_unknown",
  "provider_boundary_ignored",
  "provider_duplicate",
  "provider_empty_final",
  "provider_empty_interim",
  "provider_final",
  "provider_interim",
  "provider_invalid",
  "provider_other",
  "provider_stale",
  "provider_utterance_end",
  "provider_vad_start",
  "queue_accepted",
  "reply_cancelled",
  "reply_deferred",
  "segment_rejected",
  "utterance_discarded",
  "utterance_emitted",
] as const;
const speechCounters = [
  "audio_bytes",
  "audio_frames",
  "audio_nonzero_frames",
  "audio_sent_frames",
  "callback_accepted",
  "callback_failed",
  "callback_refused",
  "callback_started",
  "capture_close",
  "capture_error",
  "capture_open",
  "capture_reset",
  "playback_completed",
  "playback_failed",
  "playback_started",
  "playback_unknown",
  "provider_boundary_ignored",
  "provider_duplicate",
  "provider_empty_final",
  "provider_empty_interim",
  "provider_final",
  "provider_interim",
  "provider_invalid",
  "provider_other",
  "provider_stale",
  "provider_utterance_end",
  "provider_vad_start",
  "queue_accepted",
  "reply_cancelled",
  "reply_deferred",
  "segment_rejected",
  "utterance_discarded",
  "utterance_emitted",
] as const;
const speechReasons = [
  "authority_closed",
  "authorization_closed",
  "callback_invalid_response",
  "callback_refused",
  "callback_stale",
  "callback_timeout",
  "callback_transport",
  "capture_stopped",
  "character_limit",
  "complete",
  "connection_closed",
  "duration_limit",
  "fragment_limit",
  "generation_change",
  "human_speaking",
  "interim_retracted",
  "invalid_segment",
  "newer_human_turn",
  "obsolete_generation",
  "playback_failed",
  "playback_interrupted",
  "policy_closed",
  "priority_stop",
  "queue_full",
  "stale_queue",
] as const;
const speechPhases = [
  "collecting",
  "idle",
  "quarantined",
  "settling",
  "vad_grace",
  "waiting_final",
] as const;

const count = z.number().int().min(0).max(999999999);
const milliseconds = z.number().int().min(0).max(86400000);
export const speechPipelineSchema = z.object({
  version: z.literal(1),
  at: z.string().max(40).datetime({ offset: true }),
  counts: z.object(
    Object.fromEntries(speechCounters.map((key) => [key, count.optional()])),
  ),
  state: z.object({
    phase: z.enum(speechPhases),
    fragments: z.number().int().min(0).max(129),
    hasInterim: z.boolean(),
    vadPending: z.boolean(),
    ageMs: milliseconds,
  }),
  events: z
    .array(
      z.object({
        sequence: count,
        event: z.enum(speechEvents),
        generation: count,
        elapsedMs: milliseconds,
        reason: z.enum(speechReasons).optional(),
        segment: count.optional(),
        characters: z.number().int().min(0).max(8001).optional(),
        startMs: milliseconds.optional(),
        durationMs: milliseconds.optional(),
        lastWordEndMs: milliseconds.optional(),
        speechFinal: z.boolean().optional(),
      }),
    )
    .max(64),
});
